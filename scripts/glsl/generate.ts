import type { FXGLSLRenderTier } from "../../src/artifact/FXArtifact.js";
import { fractalHelpers } from "./fractalNoise.js";
import type { FXGLSLHelperDefinition } from "./helperDefinition.js";
import { LIBRARY_HELPERS } from "./library.js";
import { BASELINE_NOISE_HASH, NOISE_HASHES, STANDARD_NOISE_HASH } from "./noiseHash.js";
import { seedHashHelper } from "./seedHash.js";
import { noisedHelper, noiseHelper } from "./valueNoise.js";
import { voronoiHelpers } from "./voronoiNoise.js";

const TIERS: readonly FXGLSLRenderTier[] = ["baseline", "standard"];

/** Every GLSL helper, each after the helpers it requires. */
function catalog(): readonly FXGLSLHelperDefinition[] {
  const noise = {
    baseline: noiseHelper(BASELINE_NOISE_HASH),
    standard: noiseHelper(STANDARD_NOISE_HASH),
  };
  const noised = {
    baseline: noisedHelper(BASELINE_NOISE_HASH),
    standard: noisedHelper(STANDARD_NOISE_HASH),
  };
  return [
    ...NOISE_HASHES.map((hash) => hash.helper),
    noise.baseline,
    noise.standard,
    noised.baseline,
    noised.standard,
    ...fractalHelpers(noise, noised),
    ...NOISE_HASHES.flatMap(voronoiHelpers),
    ...NOISE_HASHES.map(seedHashHelper),
    ...LIBRARY_HELPERS,
  ];
}

/** `helpers`, checked: each name and each source once, each requirement declared before. */
function checked(helpers: readonly FXGLSLHelperDefinition[]): readonly FXGLSLHelperDefinition[] {
  const names = new Set<string>();
  const sources = new Set<string>();
  for (const helper of helpers) {
    if (names.has(helper.name) || sources.has(helper.source)) {
      throw new Error(`generate: ${helper.name} repeats a name or a source`);
    }
    for (const tier of TIERS) {
      for (const required of helper.requires[tier] ?? []) {
        if (!names.has(required.name) || required.requires[tier] === undefined) {
          throw new Error(
            `generate: ${helper.name} requires ${required.name}, not declared before on ${tier}`,
          );
        }
      }
    }
    names.add(helper.name);
    sources.add(helper.source);
  }
  return helpers;
}

function requiresTable(helpers: readonly FXGLSLHelperDefinition[], tier: FXGLSLRenderTier): string {
  const rows = helpers.flatMap((helper) => {
    const required = helper.requires[tier];
    return required === undefined
      ? []
      : [
          `    ${helper.name}: [${required.map((dependency) => JSON.stringify(dependency.name)).join(", ")}],`,
        ];
  });
  return [`  ${tier}: {`, ...rows, "  },"].join("\n");
}

/** The text of `src/helpers/glsl.ts`. */
export function generateGLSLHelpers(): string {
  const helpers = checked(catalog());
  return [
    "/**",
    " * The GLSL helpers an exported effect's shaders call, generated by `scripts/glsl` - run",
    " * `npm run generate` after changing them. {@link FX_GLSL_HELPER_REQUIRES} is the compiler's: what",
    " * each tier links each helper with.",
    " */",
    "",
    "/* eslint-disable @typescript-eslint/naming-convention -- the table is keyed by constant names */",
    "",
    'import type { FXGLSLRenderTier } from "../artifact/FXArtifact.js";',
    "",
    ...helpers.map(
      (helper) => `export const ${helper.name} =\n  ${JSON.stringify(helper.source)};\n`,
    ),
    "/** The name of a GLSL helper's constant. */",
    "export type FXGLSLHelperName =",
    ...helpers.map(
      (helper, index) =>
        `  | ${JSON.stringify(helper.name)}${index === helpers.length - 1 ? ";" : ""}`,
    ),
    "",
    "/** The helpers each tier links, each with the helpers it calls, which go before it. */",
    "export const FX_GLSL_HELPER_REQUIRES: Readonly<",
    "  Record<FXGLSLRenderTier, Readonly<Partial<Record<FXGLSLHelperName, readonly FXGLSLHelperName[]>>>>",
    "> = {",
    ...TIERS.map((tier) => requiresTable(helpers, tier)),
    "};",
    "",
  ].join("\n");
}
